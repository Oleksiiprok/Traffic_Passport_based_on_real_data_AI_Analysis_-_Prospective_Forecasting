            if vc > 1.0 and spd < 12.0:
                status = "🛑 Gridlock (Zero-Speed Jam)"
            elif vc > 1.0:
                status = "🔴 Critical Limit Exceeded"
            elif vc > 0.85:
                status = "🟡 Moderate Load"
            else:
                status = "🟢 Stable Flow"

            fc_table += f"| **{pt}** | **{vc}** | {status} | {thr} | {occ}% | {spd} |\n"

