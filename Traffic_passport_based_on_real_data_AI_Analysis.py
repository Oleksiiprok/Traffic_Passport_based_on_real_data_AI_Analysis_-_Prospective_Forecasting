        clear_output(wait=True)

        start_date = fc_start_date_widget.value
        end_date = fc_end_date_widget.value

        if start_date <= CURRENT_DATE:
            print(f"❌ Error: Forecast start date ({start_date.strftime('%m-%d-%Y')}) must be strictly AFTER today's date ({CURRENT_DATE.strftime('%m-%d-%Y')})!")
            return

        print(f"Initializing Long-Term Prospective Traffic Forecasting Pipeline (Start: {start_date.strftime('%m-%d-%Y')} | End: {end_date.strftime('%m-%d-%Y')})...")
        time.sleep(0.4)

        route = fc_route_widget.value
        ai_model = fc_ai_widget.value
