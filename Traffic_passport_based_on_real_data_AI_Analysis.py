        print("==================================================================")
        print("         PROSPECTIVE TRAFFIC PERFORMANCE & RISK FORECAST          ")
        print("==================================================================")
        print(f"• Target Corridor: {route}")
        print(f"• Forecasting Interval Window: {start_date.strftime('%m-%d-%Y')} to {end_date.strftime('%m-%d-%Y')}")
        print(f"• Core Predictive Engine: {ai_model}\n")

